def precision(m: int, f: int) -> float | None:
    return round(m / (m + f), 2) if m + f else None


def f1(p: float | None, r: float) -> float | None:
    if p is None or p + r == 0:
        return None
    return round(2 * p * r / (p + r), 2)


def verdict(p: float | None, r: float, n_gt: int, n_vi: int, rules=TRUST_RULES) -> str:
    """유형 하나의 판정. 자료 부족이 다른 조건보다 먼저."""
    if n_gt < rules["min_count"] or n_vi < rules["min_count"] or p is None:
        return "자료 부족"
    if p >= rules["trust"] and r >= rules["trust"]:
        return "믿고 써도 됨"
    if p >= rules["reference"] and r >= rules["reference"]:
        return "참고용"
    return "사람에게 물어볼 것"


