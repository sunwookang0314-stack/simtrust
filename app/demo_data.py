def load_personas() -> tuple[dict[str, list[dict]], str]:
    """서비스별 10명(재학생 5 + 취준생 5)과 출처 설명. 실제 파일이 있으면 시드 42로 고정 추출."""
    files = sorted(f for f in PERSONA_DIR.rglob("*.json") if f.name != "manifest.json") if PERSONA_DIR.is_dir() else []
    groups = {"재학생": [], "취준생": []}
    for f in files:
        try:
            p = _unwrap(json.loads(f.read_text(encoding="utf-8")))
        except (json.JSONDecodeError, UnicodeDecodeError):
            continue
        p["__id__"] = f.name.split(".")[0]
        p["__group__"] = "취준생" if f.name.startswith("J") else "재학생"
        groups[p["__group__"]].append(p)
    if len(groups["재학생"]) < 10 or len(groups["취준생"]) < 10:
        return _mock_personas(), "고정 목업 10명 · 실험 폴더에 페르소나 파일이 없음"
    rnd = random.Random(PERSONA_RECORD["seed"])
    out = {s: [] for s in SERVICES}
    for g in ("재학생", "취준생"):
        pool = rnd.sample(groups[g], 10)        # 두 서비스에 같은 사람이 겹치지 않게 10명을 나눔
        out["링커리어"] += pool[:5]
        out["캠퍼스픽"] += pool[5:]
    try:
        where = PERSONA_DIR.relative_to(REPO_ROOT)
    except ValueError:
        where = PERSONA_DIR
    return out, f"실제 파일 · {where} ({len(files)}명 중 서비스당 10명)"


